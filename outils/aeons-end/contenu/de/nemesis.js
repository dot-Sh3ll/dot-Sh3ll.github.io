function bonus(c){ // ce que le contexte du combat ajoute à la note d'une carte
  let b=0; const why=[]; const N=NEMBY[fight.nem]; const p=N&&N[2];
  if(p){
    if((p.want||[]).some(t=>c.tags.includes(t)) || (p.big&&c.type==="Spell"&&c.cost>=6)){ b+=1; why.push("Gegen "+N[0]); }
    if((p.avoid||[]).includes(c.id)) b-=3;
  }
  let mb=0;
  fight.mages.forEach(name=>{ const M=MAGEBY[name]; if(M&&M[2].some(t=>c.tags.includes(t))){ mb+=0.75; why.push("Für "+name.replace(/ \(.*/,"")); } });
  return {b:b+Math.min(mb,1),why};
}
